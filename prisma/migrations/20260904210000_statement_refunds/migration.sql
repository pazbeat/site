-- Возвраты и комиссия в строке банковской выписки.
--
-- Возврат по Kaspi нельзя узнать никак иначе: в ответе легаси-бэкенда есть
-- только признак «оплачено», состояния «отменено» в нём нет. Пока выписка не
-- загружена, отменённый платёж выглядит обычной продажей, а сертификат
-- остаётся действующим.
--
-- Комиссия объясняет разницу между оборотом и суммой, реально пришедшей на
-- счёт: у Forte это отдельная колонка, у Kaspi — «Стоимость услуг Kaspi».
ALTER TABLE "bank_statement_entries"
  ADD COLUMN IF NOT EXISTS "kind" VARCHAR(16) NOT NULL DEFAULT 'payment',
  ADD COLUMN IF NOT EXISTS "fee_kzt" INTEGER;
