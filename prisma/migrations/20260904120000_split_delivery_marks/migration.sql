-- Раздельные отметки доставки (2026-09-04).
--
-- Доставка шлёт два письма: получателю подарка и покупателю (с чеком), и
-- ставит одну отметку sent_at после обоих. Если второе письмо падало, отметки
-- не появлялось вовсе — и повтор доставки присылал ПОЛУЧАТЕЛЮ второй
-- сертификат. Для подарка это заметно хуже, чем недоставленный чек.
--
-- Уже доставленным проставляем обе отметки: их доставка завершена целиком,
-- и повторять по ним нечего.

ALTER TABLE "certificates"
  ADD COLUMN "recipient_sent_at" TIMESTAMP(3),
  ADD COLUMN "buyer_sent_at" TIMESTAMP(3);

UPDATE "certificates"
   SET "recipient_sent_at" = "sent_at",
       "buyer_sent_at" = "sent_at"
 WHERE "sent_at" IS NOT NULL;
