-- Счётчик номеров сертификатов начинается с 9001, а не с единицы.
--
-- В Altegio нумерация филиала общая с действующим сайтом, и низкие номера
-- там местами уже заняты его историей: 2026-08-26 выпуск WM0006 получил
-- «Gift card with such number already exists», продажа не создалась, а
-- покупателю ушёл номер, которого в CRM нет. Занятые номера идут вразнобой,
-- поэтому счётчик поднимаем в заведомо свободный диапазон.
--
-- Только поднимаем: опустить счётчик нельзя — выданные номера повторятся.
ALTER TABLE "salons" ALTER COLUMN "last_cert_serial" SET DEFAULT 9000;
UPDATE "salons" SET "last_cert_serial" = 9000 WHERE "last_cert_serial" < 9000;
