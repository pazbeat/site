-- Отметка о пробитом фискальном чеке по оплате Kaspi (2026-09-04).
--
-- Бухгалтер вела это в своей таблице строкой «пробить чеки по каспи» с суммой
-- и количеством, и ниже «пробила 25.08.2026». Здесь то же самое, но
-- привязанное к конкретным заказам: по дню целиком нельзя ни проверить, что
-- ничего не забыто, ни понять, какой именно платёж остался без чека.

ALTER TABLE "orders"
  ADD COLUMN "fiscal_receipt_at" TIMESTAMP(3),
  ADD COLUMN "fiscal_receipt_by" VARCHAR(160);

-- Список «что осталось пробить» строится по этой паре
CREATE INDEX "orders_fiscal_receipt_idx"
  ON "orders" ("payment_provider", "fiscal_receipt_at");
