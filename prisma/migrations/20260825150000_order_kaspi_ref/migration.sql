-- Короткий номер заказа для Kaspi.
--
-- Приложение Kaspi проверяет номер по маске кабинета мерчанта и отбрасывает
-- всё, что в неё не влезло, ДО обращения к бэкенду. Внутренний номер заказа
-- (cuid, 25 знаков) в маску не проходил: покупатель видел «проверьте
-- правильность ввода данных», а бэкенд об этом заказе даже не спрашивали.
-- Выяснено 2026-08-25 сравнением с тестовым номером Kaspi 001AA01.
ALTER TABLE "orders" ADD COLUMN "kaspi_ref" VARCHAR(16);
CREATE UNIQUE INDEX "orders_kaspi_ref_key" ON "orders"("kaspi_ref");
