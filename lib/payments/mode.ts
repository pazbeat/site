/**
 * Включена ли демо-оплата. **Единственное место**, где это решается: раньше
 * условие `PAYMENT_MOCK === "1"` было переписано в шести файлах, и каждое
 * значило чуть своё.
 *
 * Отдельный модуль, а не функция в `index.ts`, — чтобы `mock.ts` не импортировал
 * `index.ts`, который импортирует `mock.ts`: цикл ESM разрешает, но ломается он
 * молча и в самый неудачный момент.
 *
 * В production флаг не действует, даже если его случайно оставили в окружении.
 * Так и случилось: `PAYMENT_MOCK=1` пережил отладку и до 2026-09-04 стоял на
 * боевом сервере. Бесплатных сертификатов он не давал (демо-провайдер доступен
 * только администратору), но выключал фоновый добор оплат в
 * `lib/kaspi-poller.ts` — и покупатель, закрывший вкладку сразу после оплаты,
 * оставался без сертификата, а через 15 минут получал письмо «вы не завершили
 * покупку». Документация при этом утверждала, что в проде флаг игнорируется;
 * теперь это правда, а не обещание.
 */
export function mockEnabled(): boolean {
  return (
    process.env.PAYMENT_MOCK === "1" && process.env.NODE_ENV !== "production"
  );
}
