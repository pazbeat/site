/**
 * Отметка «подарок уже открыт» для экрана «Вам подарок» (`/success`,
 * components/gift-reveal.tsx). Файл без серверных зависимостей: имя cookie
 * считают и страница (читает), и компонент (ставит).
 *
 * Отметок две, и нужны обе:
 * - cookie — её читает СЕРВЕР и сразу рендерит открытый экран. Без неё до
 *   гидрации показывалась закрытая коробка, и уже открытый подарок при
 *   перезагрузке «закрывался» на долю секунды, а на медленном телефоне — дольше;
 * - sessionStorage — запасной путь, если cookie браузер не сохранил: тогда
 *   открытое состояние включается сразу после гидрации.
 *
 * В имени cookie не токен заказа, а его хэш: токен открывает сертификат, и
 * гонять его заголовком с каждым запросом к сайту незачем. Cookie сессионная
 * (без срока): закрыл браузер — коробка снова закрыта, как и с sessionStorage.
 */

import { fnv1a } from "./gift-palettes";

/** Ключ sessionStorage: префикс + токен заказа (живёт только в этой вкладке). */
export const GIFT_OPENED_STORAGE_PREFIX = "imbir-gift-opened:";

export function giftOpenedCookieName(token: string): string {
  return `imbir-gift-opened-${fnv1a(token).toString(36)}`;
}
