/**
 * Короткий номер заказа для Kaspi.
 *
 * Приложение Kaspi проверяет номер по маске, заданной в кабинете мерчанта, и
 * отбрасывает не подошедший ДО обращения к бэкенду. Наш внутренний номер —
 * cuid в 25 знаков — в маску не проходил: покупатель видел «проверьте
 * правильность ввода данных», а бэкенд об этом заказе даже не спрашивали
 * (доказано 2026-08-25: журнал моста пуст, обращений не было ни одного).
 *
 * Формат восстановлен по квитанциям действующего сайта:
 *
 *     10512210190824140899
 *     10512210190825170883
 *
 * Двадцать цифр, без букв: постоянная часть `1051221019`, дальше дата и время.
 * Поэтому наш номер тоже двадцатизначный и тоже из одних цифр — так он
 * заведомо проходит ту же маску. Буквы подтверждены только тестовым счётом
 * Kaspi `001AA01`, а тестовые счета маску могут и обходить; рисковать на этом
 * нечем.
 */

/**
 * Первая цифра, отличающая наши номера от номеров действующего сайта.
 *
 * Это не украшение, а защита от подмены заказа. Kaspi спрашивает про номер
 * СТАРЫЙ сайт: тот ищет заказ у себя и только не найдя — обращается к нам.
 * Совпади номера — старый нашёл бы свой заказ, до нас дело бы не дошло, и
 * покупатель оплатил бы чужую сумму, не заметив подмены. Их номера начинаются
 * с единицы, наши — с девятки: пересечение невозможно, а не маловероятно.
 */
const PREFIX = "9";

/** Как у действующего сайта — под ту же маску кабинета Kaspi. */
export const ORDER_REF_LENGTH = 20;

const RANDOM_PART = ORDER_REF_LENGTH - PREFIX.length;

export const ORDER_REF_REGEX = new RegExp(`^${PREFIX}\\d{${RANDOM_PART}}$`);

export function isOrderRef(value: string): boolean {
  return ORDER_REF_REGEX.test(normalizeOrderRef(value));
}

/** Приводит к каноническому виду: без пробелов по краям. */
export function normalizeOrderRef(value: string): string {
  return value.trim();
}

/**
 * Случайный номер. Случайный, а не по счётчику и не по времени: у
 * действующего сайта в номер зашиты дата и время, и такие номера можно
 * подбирать перебором, разглядывая чужие суммы в приложении Kaspi.
 * Девятнадцать случайных цифр этого не позволяют.
 */
export function generateOrderRef(random: () => number = Math.random): string {
  let out = PREFIX;
  for (let i = 0; i < RANDOM_PART; i += 1) {
    out += String(Math.floor(random() * 10));
  }
  return out;
}
