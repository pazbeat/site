import "server-only";
import { headers } from "next/headers";

/**
 * Разовый ключ, которым подписаны разрешённые скрипты страницы.
 *
 * Ставит его `proxy.ts` в заголовок запроса, а политика безопасности
 * (`lib/security.ts`) пускает только скрипты с этим ключом. Любой встроенный
 * `<script>` без него браузер в проде молча выбросит — включая безобидную
 * микроразметку для поисковиков. В разработке этого не видно: там политика
 * ослаблена ради горячей перезагрузки, поэтому проверять только на боевой
 * сборке.
 */
export async function scriptNonce(): Promise<string | undefined> {
  return (await headers()).get("x-nonce") ?? undefined;
}
